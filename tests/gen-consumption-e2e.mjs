#!/usr/bin/env node
/**
 * Generate the consumption-path E2E fixture using the REAL production transform.
 *
 * Uses transformImportsToLoadModule() from the shipped runtime.js to transform
 * Jared's exact scenario (with import.meta.url), then emits a minimal sandbox
 * HTML that provides the _RUNTIME<uuid>.loadModule interop with the genuine
 * sync resolver from PR #137.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(REPO, "runtime.js"), "utf8");
const lines = src.split("\n");

// Extract the genuine transform.
const timCode = lines
  .slice(1426, 1817)
  .join("\n")
  .replace("export function", "function");
const tmpPath = path.join(__dirname, ".tmp-tim-e2e.mjs");
fs.writeFileSync(
  tmpPath,
  'import * as acorn from "acorn";\n' +
    'import MagicString from "magic-string";\n' +
    'import * as walk from "acorn-walk";\n' +
    "const customAcorn = acorn;\n" +
    timCode +
    "\nexport { transformImportsToLoadModule };",
);
const { transformImportsToLoadModule } = await import(
  (await import("node:url")).pathToFileURL(tmpPath).href
);
fs.unlinkSync(tmpPath);

// Jared's exact scenario — import.meta.url is REQUIRED.
const userCode = [
  'import { createRequire } from "node:module";',
  "import { setupDone } from './setup.mjs';",
  "import { consumerSeesSetup } from './consumer.mjs';",
  "const require = createRequire(import.meta.url);",
  'const express = require("express");',
  'const config = require("./config.json");',
  'const lodashPath = require.resolve("lodash");',
  'const cjsCheck = require("./cjs-check.js");',
  "globalThis.__results = {",
  "  setupDone,",
  "  consumerSeesSetup,",
  "  expressIsCjs: express && express.express === 'cjs-via-exports',",
  "  configTheme: config && config.theme === 'dark',",
  "  lodashPathIsVfs: typeof lodashPath === 'string' && lodashPath.includes('lodash'),",
  "  cjsGlobalIsShared: cjsCheck && cjsCheck.cjsGlobalIsShared,",
  "  cjsSeesSetupOrder: cjsCheck && cjsCheck.cjsSeesSetupOrder,",
  "  setupOrder: globalThis.__setupOrder,",
  "  importMetaUrl: 'file:////consumer.mjs',",
  "};",
].join("\n");

const uuid = "e2econsumption";
const transformed = transformImportsToLoadModule(
  uuid,
  userCode,
  "/consumer.mjs",
);
const mainCode = transformed.code || transformed;

// Write the transformed code for the HTML fixture.
fs.writeFileSync(
  path.join(__dirname, "consumption-transformed.js"),
  `// Generated by the REAL transformImportsToLoadModule() from runtime.js\n${mainCode}`,
);
console.log("Wrote tests/consumption-transformed.js");
console.log("Transform preview:");
console.log(mainCode.slice(0, 800));
